export type Page = {
  id: number;
  text: string;
  pageNumber: string;
  paragraphRange: string; // 例: "第1・2だん落"
  // pageNumber はタイトル画面のカードに出す短い見出し
};

// 読みの力（光村4年「読むこと」説明文の指導事項とテストの問われ方に合わせた5つ）。
// キーは物語文アプリ（ごんぎつね など）と共通にして、画面のコードを同じにしている。
// 説明文なので、名前と中身は説明文用に読みかえる：
//   kotoba = ことばの意味（つなぎ言葉をふくむ） / yousu = 書かれていること / kimochi = だん落の役わり
//   henka = くらべて読む（アップとルーズの対比） / kangae = 筆者の考え
export type Skill = 'kotoba' | 'yousu' | 'kimochi' | 'henka' | 'kangae';

