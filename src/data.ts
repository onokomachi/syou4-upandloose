// 読みまちがいの型。選択問題のまちがいの選択肢は、どれか1つの型に当たるように作る。
// 子どもがまちがえたとき、「なぜまちがえたか」をこの型で伝える。キーは物語文アプリと共通。
export type Misread = 'imagine' | 'scene' | 'person' | 'surface';

export const MISREADS: Record<Misread, { label: string; advice: string }> = {
  imagine: { label: '本文に書いていないことを想像で決める', advice: 'それは本文に書いてあるかな？ 書いていないことを想像で決めていないか、たしかめよう。' },
  scene:   { label: 'ほかのだん落のこととまぜる', advice: 'それは、ほかのだん落に書いてあることじゃないかな？ 問われているだん落にもどって読もう。' },
  person:  { label: 'アップとルーズ・分かることと分からないことを とりちがえる', advice: 'アップ（ある部分を大きく）とルーズ（広いはんい）のどちらのことか、分かることか分からないことか、もう一度たしかめよう。' },
  surface: { label: '言葉の一部分だけで決める', advice: '言葉の一部分だけで決めていないかな？ 前後の文もいっしょに読もう。' },
};

export type Question = {
  id: number;
  pageId: number;
  skill: Skill;
  type: 'extract' | 'choice' | 'free';
  question: string;
  targetText?: string; // 下線を引く位置。ぬき出し問題では使わず、選択問題で「下線部について問う」ときのみ使う。
  answer?: string[] | number;
  choices?: string[];
  misread?: (Misread | null)[]; // choices と同じ並び。正解の位置だけ null
  sampleAnswer?: string;
  points?: string[]; // 記述問題の「ここが書けていればOK」（自分で見くらべる）
  hint: string;   // ヒント①
  hint2?: string; // ヒント②（よりくわしい）
  charCount?: number; // 文字数指定ぬき出し（指定時は厳密に一致）
};

export type Kanji = {
  char: string;
  reading: string;
  meaning: string;
  pageId: number;
  example?: string;
};

// 説明文の「だん落」構成。section は 初め / 中 / 終わり（4年生用語）。
// feeling は画面では「読みどころ」として出る（物語文アプリと共通の形。説明文では気持ちではなく読むポイント）。
export type Scene = {
  num: number;
  pageId: number;
  section: 'hajime' | 'naka' | 'owari';
  role: string;     // このだん落のはたらき
  summary: string;  // 書かれていること
  feeling?: {
    who: 'up' | 'loose' | 'writer' | 'theme';
    point: string;    // 読みどころ
    deep: string;     // さらに深い読み（テスト頻出の問い）
  };
};

// 後方互換のため Paragraph 名でも参照できるようにする
